<?php

declare(strict_types=1);

namespace Cbox\Cms\Tooling\Protocol\Domain;

use Cbox\Cms\Generators\Codec\Domain\Dto\CodecContract;
use Cbox\Cms\Generators\Codec\Domain\TypeScriptEmitter;
use Cbox\Cms\Generators\Generation\Domain\Dto\GeneratedFile;
use Cbox\Cms\Generators\Generation\Domain\Dto\GenerationResult;
use Cbox\Cms\Generators\Generation\Domain\GenerateErrorCode;
use Cbox\Cms\Generators\Generation\Domain\GenerationFailed;

/**
 * The kernel contracts the component kit reads (GUARDRAILS 2.2, 8; PRD 11.12, 14.1): the type
 * editor descriptor, which the kit's form renders a type from and validates with, through the
 * validation runtime. composer generate:protocol writes, into TYPESCRIPT_DIRECTORY, the runtime
 * module and a module per contract of PROTOCOL_CODECS, which the result owns. The directory sits
 * below the kit's generated directory next to what `npm run generate:tokens` writes there, which
 * the result leaves alone.
 */
final readonly class UiKitSchemas
{
    /** Where the TypeScript goes, relative to the root of cboxdk/cms; composer generate:protocol owns it. */
    public const string TYPESCRIPT_DIRECTORY = 'js/ui-kit/src/generated/protocol';

    /** The runtime module of the validators, below the TypeScript directory. */
    public const string RUNTIME = 'validation.ts';

    /**
     * The kernel contracts the kit reads, by codec class: the type editor descriptor, which its
     * form renders a type from.
     *
     * @var list<string>
     */
    public const array PROTOCOL_CODECS = ['TypeEditorCodecV1'];

    /**
     * In TYPESCRIPT_DIRECTORY, the runtime module and the module of each kernel contract of
     * PROTOCOL_CODECS among $protocol, which the result owns. A codec of PROTOCOL_CODECS that no
     * contract has is refused.
     *
     * @param  list<CodecContract>  $protocol  the kernel's contracts; those of PROTOCOL_CODECS get a module
     *
     * @throws GenerationFailed with GenerateErrorCode::InvalidOutput or GenerateErrorCode::NameCollision
     */
    public static function result(array $protocol, string $runtime): GenerationResult
    {
        $files = [self::TYPESCRIPT_DIRECTORY.'/'.self::RUNTIME => new GeneratedFile(self::TYPESCRIPT_DIRECTORY.'/'.self::RUNTIME, $runtime)];
        $found = [];

        foreach ($protocol as $contract) {
            if (! in_array($contract->codecClass, self::PROTOCOL_CODECS, true)) {
                continue;
            }

            $found[] = $contract->codecClass;
            $name = (string) preg_replace('/Codec(V[0-9]+)\z/', '$1', $contract->codecClass);
            $module = TypeScriptEmitter::emit(
                $contract,
                self::TYPESCRIPT_DIRECTORY.'/'.$name.'.ts',
                './validation',
                [
                    sprintf('A contract of the kernel, %s, as TypeScript (GUARDRAILS 2.2): its JSON form, which the', $name),
                    sprintf('kernel\'s codec %s writes, and a validator that checks a JSON value against', $contract->codecClass),
                    'every rule of its JSON Schema. The component kit\'s form renders a type from it.',
                    '',
                    'Generated by composer generate:protocol from the JSON Schemas of cboxdk/cms.',
                    'Do not edit this file: change the schema and run composer generate:protocol.',
                ],
            );
            $files[$module->path] = $module;
        }

        $missing = array_diff(self::PROTOCOL_CODECS, $found);

        if ($missing !== []) {
            throw GenerationFailed::because(GenerateErrorCode::InvalidOutput, sprintf('The component kit reads the kernel contract of %s, which the kernel schemas do not have.', implode(', ', $missing)));
        }

        ksort($files, SORT_STRING);

        return new GenerationResult(array_values($files), [self::TYPESCRIPT_DIRECTORY]);
    }
}
