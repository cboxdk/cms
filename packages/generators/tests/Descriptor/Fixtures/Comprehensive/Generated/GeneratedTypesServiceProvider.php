namespace Cbox\Cms\Generators\Tests\Descriptor\Fixtures\Comprehensive\Generated;

use Cbox\Cms\Contracts\Codecs\RecordCodecs;
use Cbox\Cms\Contracts\Schema\TypeCatalog;
use Cbox\Cms\Contracts\Validation\TypeValidators;
use Cbox\Cms\Generators\Tests\Descriptor\Fixtures\Comprehensive\Generated\Records\ShopProduct\ShopProductFactory;
use Cbox\Cms\Generators\Tests\Descriptor\Fixtures\Comprehensive\Generated\Records\ShopProduct\ShopProductRecordFactory;
use Illuminate\Support\ServiceProvider;
use Override;

/**
 * Binds what the generated code gives the kernel and the owners' code (PRD 8.9, 11.12): the
 * TypeCatalog contract to the generated catalog, the TypeValidators contract to the generated
 * validators, the RecordCodecs contract to the generated record codecs, and each type's record
 * factory interface to the factory of its composite record, with every extender's fields.
 * Registers the generated migrations of the type tables with the migrator; they run with migrate,
 * never on their own. Register it once in the application.
 *
 * Generated by cms:generate from the blueprint v1 files below the schema roots. Do not edit
 * this file: change the blueprints and run cms:generate.
 */
final class GeneratedTypesServiceProvider extends ServiceProvider
{
    #[Override]
    public function register(): void
    {
        $this->app->singleton(TypeCatalog::class, GeneratedTypeCatalog::class);
        $this->app->singleton(TypeValidators::class, GeneratedTypeValidators::class);
        $this->app->singleton(RecordCodecs::class, GeneratedRecordCodecs::class);
        $this->app->singleton(ShopProductRecordFactory::class, ShopProductFactory::class);
    }

    public function boot(): void
    {
        $this->loadMigrationsFrom(__DIR__.'/../migrations/cms');
    }
}
