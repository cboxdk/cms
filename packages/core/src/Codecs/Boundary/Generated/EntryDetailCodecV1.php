        $json->visibility = $object->visibility->value;
        $json->window = $object->window instanceof TimeWindow ? $this->encodeTimeWindow($object->window) : null;

        return $json;
    }

    private function decodeEntryPlacementLocale(mixed $value, FieldPath $path): EntryPlacementLocale
    {
        $object = JsonValues::object($value, $path, ['canonical', 'locale', 'slug', 'visibility', 'window']);

        return JsonValues::build($path, fn (): EntryPlacementLocale => new EntryPlacementLocale(
            locale: JsonValues::required($object, 'locale', $path, static fn (mixed $value, FieldPath $at): Locale => JsonValues::value($value, $at, static fn (string $text): Locale => new Locale($text))),
            slug: JsonValues::required($object, 'slug', $path, static fn (mixed $value, FieldPath $at): Slug => JsonValues::value($value, $at, static fn (string $text): Slug => new Slug($text))),
            visibility: JsonValues::required($object, 'visibility', $path, static fn (mixed $value, FieldPath $at): Visibility => JsonValues::enum($value, $at, Visibility::class)),
            window: JsonValues::present($object, 'window', $path, $this->decodeTimeWindow(...)),
            canonical: JsonValues::required($object, 'canonical', $path, static fn (mixed $value, FieldPath $at): bool => JsonValues::boolean($value, $at)),
        ));
    }

    private function encodeTimeWindow(TimeWindow $object): stdClass
    {
        $json = new stdClass;
        $json->from = $object->from instanceof DateTimeImmutable ? JsonValues::encodeDatetime($object->from) : null;
        $json->until = $object->until instanceof DateTimeImmutable ? JsonValues::encodeDatetime($object->until) : null;

        return $json;
    }

    private function decodeTimeWindow(mixed $value, FieldPath $path): TimeWindow
    {
        $object = JsonValues::object($value, $path, ['from', 'until']);

        return JsonValues::build($path, static fn (): TimeWindow => new TimeWindow(
            from: JsonValues::present($object, 'from', $path, static fn (mixed $value, FieldPath $at): DateTimeImmutable => JsonValues::datetime($value, $at)),
            until: JsonValues::present($object, 'until', $path, static fn (mixed $value, FieldPath $at): DateTimeImmutable => JsonValues::datetime($value, $at)),
        ));
    }
